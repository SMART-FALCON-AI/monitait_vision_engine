// Get translation with English fallback
function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
}

// Loading state helpers for buttons
function _btnLoading(btn) {
    if (!btn) try { btn = event && event.target && event.target.closest('button, .control-button, .camera-btn, .discovery-button'); } catch(e) {}
    if (!btn || btn.classList.contains('btn-loading')) return null;
    var orig = btn.innerHTML;
    btn.classList.add('btn-loading');
    btn.disabled = true;
    btn.innerHTML = '<span class="btn-spinner"></span>' + orig;
    return { btn: btn, orig: orig };
}
function _btnDone(state) {
    if (!state) return;
    state.btn.classList.remove('btn-loading');
    state.btn.disabled = false;
    state.btn.innerHTML = state.orig;
}

// Apply translations to all elements with data-i18n attribute
function applyLanguage(lang) {
    if (lang) {
        currentLang = lang;
        localStorage.setItem('monitaqc_lang', lang);
    }
    // Set RTL for Arabic and Persian
    var isRTL = (currentLang === 'ar' || currentLang === 'fa');
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    // 4.0.18 — propagate the lang code onto <html> so CSS selectors like
    // `html[lang="fa"]` can swap fonts (Vazir for Persian, Badr for Arabic, etc.).
    // Without this, font-family overrides keyed to language never fire.
    document.documentElement.lang = currentLang;

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        var prefix = el.getAttribute('data-i18n-prefix') || '';
        var val = t(key);
        // 4.0.268 — graceful fallback: t() echoes the key back when it is
        // undefined in EVERY language. Never paint a raw key name (e.g.
        // "pro_camera_discovery") into the UI — leave the element's original
        // hardcoded (English) text so the worst case is untranslated, not broken.
        if (val === key) return;
        el.textContent = prefix + val;
    });
    // Update all data-i18n-placeholder elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        var pk = el.getAttribute('data-i18n-placeholder');
        var pv = t(pk);
        if (pv === pk) return;   // undefined → keep original placeholder
        el.placeholder = pv;
    });
    // Update language selector display
    var langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = currentLang;
}
